// Rebuilds docs/js/search-index.js from the pages themselves, so search never
// drifts from page content. Run after editing any page: node scripts/build-search-index.js
const fs = require('fs');
const path = require('path');

const docsDir = path.join(__dirname, '..', 'docs');
const MAX_WORDS_PER_ENTRY = 60;

function stripTags(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&ndash;|&mdash;/g, '-')
    .replace(/&amp;/g, '&').replace(/&gt;/g, '>').replace(/&lt;/g, '<')
    .replace(/&[a-z]+;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function firstWords(text, count) {
  return text.split(' ').slice(0, count).join(' ');
}

const entries = [];
const pageFiles = fs.readdirSync(docsDir).filter(f => f.endsWith('.html')).sort();

for (const file of pageFiles) {
  const html = fs.readFileSync(path.join(docsDir, file), 'utf8');
  const pageTitle = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [, file])[1];
  const pageName = stripTags(pageTitle);
  const goal = stripTags((html.match(/class="goal__text">([\s\S]*?)<\/p>/) || [, ''])[1]);
  entries.push({ title: pageName, page: pageName, file, anchor: '', text: goal });

  const headingPattern = /<h([23])[^>]*\sid="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/g;
  const headings = [...html.matchAll(headingPattern)];
  headings.forEach((heading, i) => {
    const sectionEnd = i + 1 < headings.length ? headings[i + 1].index : html.length;
    const sectionBody = html.slice(heading.index + heading[0].length, sectionEnd);
    entries.push({
      title: stripTags(heading[3]),
      page: pageName,
      file,
      anchor: heading[2],
      text: firstWords(stripTags(sectionBody), MAX_WORDS_PER_ENTRY),
    });
  });
}

const output =
  '/* Generated by scripts/build-search-index.js. Do not edit by hand. */\n' +
  'window.WAP_SEARCH_INDEX = [\n' +
  entries.map(e => '  ' + JSON.stringify(e)).join(',\n') +
  '\n];\n';
fs.writeFileSync(path.join(docsDir, 'js', 'search-index.js'), output);
console.log(`indexed ${entries.length} entries from ${pageFiles.length} pages`);
