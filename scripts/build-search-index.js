// Rebuilds docs/js/search-index.js from the pages and plugin data, so search never
// drifts from page content. Run after editing any page: node scripts/build-search-index.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const docsDir = path.join(__dirname, '..', 'docs');
const pluginsDataFile = path.join(docsDir, 'js', 'plugins-data.js');
const PLUGINS_PAGE_FILE = 'plugins.html';
const PLUGINS_PAGE_NAME = 'Plugins';

const NAMED_ENTITIES = {
  ndash: '-', mdash: '-', nbsp: ' ', rarr: '->', larr: '<-', times: 'x', deg: '°',
  quot: '"', apos: "'", gt: '>', lt: '<', hellip: '...', middot: '·', plusmn: '±',
};

function decodeEntities(text) {
  return text
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number(dec)))
    .replace(/&([a-z]+);/gi, (entity, name) => {
      if (name === 'amp') return entity;
      return name in NAMED_ENTITIES ? NAMED_ENTITIES[name] : ' ';
    })
    .replace(/&amp;/g, '&');
}

function stripTags(html) {
  const withoutMarkup = html
    .replace(/<script[\s\S]*?<\/script>/g, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/g, ' ')
    .replace(/<[^>]+>/g, ' ');
  return decodeEntities(withoutMarkup).replace(/\s+/g, ' ').trim();
}

function contentEndIndex(html) {
  const candidates = [html.indexOf('<footer class="page-foot"'), html.indexOf('</main>')]
    .filter(index => index !== -1);
  return candidates.length ? Math.min(...candidates) : html.length;
}

function sectionEntriesForPage(file) {
  const html = fs.readFileSync(path.join(docsDir, file), 'utf8');
  const pageName = stripTags((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [, file])[1]);
  const goal = stripTags((html.match(/class="goal__text">([\s\S]*?)<\/p>/) || [, ''])[1]);
  const entries = [{ type: 'section', title: pageName, page: pageName, file, anchor: '', text: goal }];

  const contentEnd = contentEndIndex(html);
  const headingPattern = /<h([23])[^>]*\sid="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/g;
  const headings = [...html.matchAll(headingPattern)].filter(heading => heading.index < contentEnd);
  headings.forEach((heading, i) => {
    const sectionEnd = i + 1 < headings.length ? headings[i + 1].index : contentEnd;
    entries.push({
      type: 'section',
      title: stripTags(heading[3]),
      page: pageName,
      file,
      anchor: heading[2],
      text: stripTags(html.slice(heading.index + heading[0].length, sectionEnd)),
    });
  });
  return entries;
}

function loadPluginData() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(pluginsDataFile, 'utf8'), sandbox);
  return { plugins: sandbox.window.WAP_PLUGINS || [], pageTitles: sandbox.window.WAP_PLUGIN_PAGES || {} };
}

function pluginEntries() {
  const { plugins, pageTitles } = loadPluginData();
  return plugins.map(plugin => ({
    type: 'plugin',
    title: plugin.name,
    vendor: plugin.vendor,
    category: plugin.category,
    page: PLUGINS_PAGE_NAME,
    file: PLUGINS_PAGE_FILE,
    anchor: '',
    isUsedInGuide: plugin.usedOn.length > 0,
    text: plugin.usedOn.map(slug => pageTitles[slug] || slug).join(', '),
  }));
}

const pageFiles = fs.readdirSync(docsDir).filter(f => f.endsWith('.html')).sort();
const sectionEntries = pageFiles.flatMap(sectionEntriesForPage);
const entries = sectionEntries.concat(pluginEntries());

const output =
  '/* Generated by scripts/build-search-index.js. Do not edit by hand. */\n' +
  'window.WAP_SEARCH_INDEX = [\n' +
  entries.map(e => '  ' + JSON.stringify(e)).join(',\n') +
  '\n];\n';
fs.writeFileSync(path.join(docsDir, 'js', 'search-index.js'), output);
console.log(`indexed ${sectionEntries.length} sections from ${pageFiles.length} pages + ${entries.length - sectionEntries.length} plugins`);
